"""Execution rails validating tool calls, database operations, and student isolation."""

from __future__ import annotations

import logging
from typing import Any, ClassVar

from app.guardrails.models import RailCheckResult, RailType

logger = logging.getLogger(__name__)


class ExecutionRails:
    """Enforces authorization, tool boundaries, and data isolation before and after tool execution."""

    PERMITTED_TOOLS: ClassVar[set[str]] = {
        "retrieve_documents",
        "get_concept_mastery",
        "record_evidence",
        "generate_quiz",
        "grade_quiz",
        "get_recommendations",
        "get_analytics",
        "socratic_turn",
        "search_hybrid",
    }

    SQL_INJECTION_KEYWORDS: ClassVar[set[str]] = {
        "drop table",
        "drop database",
        "alter table",
        "truncate table",
        "delete from students",
        "delete from concept_mastery",
        "union select",
        "--",
    }

    def validate_tool_invocation(
        self,
        tool_name: str,
        tool_args: dict[str, Any],
        student_id: str,
    ) -> RailCheckResult:
        """Verify tool authorization, student isolation, and argument safety before execution."""
        # 1. Tool whitelisting
        if tool_name not in self.PERMITTED_TOOLS:
            logger.warning("Attempted invocation of unauthorized tool: %s", tool_name)
            return RailCheckResult(
                allowed=False,
                rail_type=RailType.EXECUTION,
                reason=f"Tool {tool_name!r} is not permitted for execution.",
                violation_code="UNAUTHORIZED_TOOL",
            )

        # 2. Student isolation enforcement
        target_student = tool_args.get("student_id")
        if target_student and str(target_student) != str(student_id):
            logger.error(
                "Cross-student tool execution attempt blocked! Actor: %s, Target: %s",
                student_id,
                target_student,
            )
            return RailCheckResult(
                allowed=False,
                rail_type=RailType.EXECUTION,
                reason="Cross-student data manipulation is strictly prohibited.",
                violation_code="CROSS_STUDENT_ACCESS",
            )

        # 3. SQL injection / Malicious payload check in string arguments
        for k, v in tool_args.items():
            if isinstance(v, str):
                v_lower = v.lower()
                for keyword in self.SQL_INJECTION_KEYWORDS:
                    if keyword in v_lower:
                        return RailCheckResult(
                            allowed=False,
                            rail_type=RailType.EXECUTION,
                            reason=f"Argument {k!r} contains suspicious database command: {keyword!r}.",
                            violation_code="MALICIOUS_TOOL_ARGUMENT",
                        )

        return RailCheckResult(allowed=True, rail_type=RailType.EXECUTION)

    def validate_tool_output(self, tool_name: str, output: Any) -> RailCheckResult:
        """Validate output generated by a tool before returning it to the LLM or agent."""
        if output is None:
            return RailCheckResult(allowed=True, rail_type=RailType.EXECUTION)

        # Ensure tool output does not contain raw database errors or stack traces
        if isinstance(output, str):
            if "Traceback (most recent call last)" in output or "Internal Server Error" in output:
                return RailCheckResult(
                    allowed=False,
                    rail_type=RailType.EXECUTION,
                    reason="Tool generated an unhandled internal exception trace.",
                    violation_code="TOOL_ERROR_LEAKAGE",
                )

        return RailCheckResult(allowed=True, rail_type=RailType.EXECUTION)
